export const complianceTemplate: ReportTemplate = {
  type: "compliance",
  label: "Compliance & Audit",
  description: "Audit-ready report with data provenance, form compliance pass/fail, and structured error logs for regulatory review.",
  supportedFormats: ["json", "markdown", "html"],

  render(data: ReportData, format: ExportFormat): string {
    if (format === "json") return renderJson(data);
    if (format === "markdown") return renderMarkdown(data);
    return renderHtml(data);
  },
};
