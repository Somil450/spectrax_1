import type { ReportTemplate, ReportData, ExportFormat } from "../../types/report";

function safe(value: unknown, fallback = "N/A"): string {
  if (value === null || value === undefined) return fallback;
  if (typeof value === "number" && !Number.isFinite(value)) return fallback;
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#x27;");
}

function fmt(seconds: number): string {
  const m = Math.floor(seconds / 60);
  const s = Math.floor(seconds % 60);
  return `${m}:${String(s).padStart(2, "0")}`;
}

function renderJson(data: ReportData): string {
  const output = {
    reportType: "compliance",
    generatedAt: new Date().toISOString(),
    version: "1.0",
    provenance: {
      system: "SpectraX",
      version: "1.0.0",
      dataSource: "on-device pose estimation pipeline",
      generatedBy: data.user?.displayName ?? "anonymous",
    },
    session: {
      exercise: data.session?.exerciseName ?? null,
      duration: data.session?.duration ?? null,
      timestamp: data.session?.timestamp ?? null,
      totalReps: data.session?.totalReps ?? null,
      accuracy: data.session?.accuracy !== undefined ? Math.round(data.session.accuracy * 100) / 100 : null,
      totalScore: data.session?.totalScore ?? null,
      frames: data.session?.totalFrames ?? null,
    },
    formCompliance: data.biomechanics
      ? {
          repCount: data.biomechanics.repScores.length,
          averageScore: Math.round(data.biomechanics.averageScore * 100) / 100,
          scoreDistribution: {
            min: Math.round(data.biomechanics.minScore * 100) / 100,
            max: Math.round(data.biomechanics.maxScore * 100) / 100,
            standardDeviation: calculateStdDev(data.biomechanics.repScores),
          },
          tempoRatio: data.biomechanics.tempoRatio ?? null,
        }
      : null,
    riskAssessment: data.risk
      ? {
          riskIndex: data.risk.riskIndex,
          fatigueIndex: data.risk.fatigueIndex,
          asymmetryScore: data.risk.asymmetryScore,
          snapshots: data.risk.riskHistory.length,
        }
      : null,
    errors: data.session?.mistakes
      ? Object.entries(data.session.mistakes)
          .map(([issue, count]) => ({ issue, count }))
          .sort((a, b) => b.count - a.count)
      : [],
  };
  return JSON.stringify(output, null, 2);
}

function calculateStdDev(values: number[]): number | null {
  if (values.length < 2) return null;
  const mean = values.reduce((a, b) => a + b, 0) / values.length;
  const variance = values.reduce((sum, v) => sum + (v - mean) ** 2, 0) / values.length;
  return Math.round(Math.sqrt(variance) * 100) / 100;
}

function renderMarkdown(data: ReportData): string {
  const s = data.session;
  const accuracy = s?.accuracy !== undefined ? Math.round(s.accuracy * 100) / 100 : null;

  const lines: string[] = [
    `# Compliance & Audit Report`,
    ``,
    `## Data Provenance`,
    ``,
    `| Field | Value |`,
    `|-------|-------|`,
    `| System | SpectraX |`,
    `| Version | 1.0.0 |`,
    `| Data Source | on-device pose estimation pipeline |`,
    `| Generated By | ${safe(data.user?.displayName ?? "anonymous")} |`,
    `| Generated At | ${new Date().toISOString()} |`,
    ``,
    `## Session Summary`,
    ``,
    `| Field | Value |`,
    `|-------|-------|`,
    `| Exercise | ${safe(s?.exerciseName)} |`,
    `| Duration | ${fmt(s?.duration ?? 0)} |`,
    `| Timestamp | ${s?.timestamp ? new Date(s.timestamp).toISOString() : "N/A"} |`,
    `| Total Reps | ${safe(s?.totalReps)} |`,
    `| Accuracy | ${accuracy !== null ? accuracy + "%" : "N/A"} |`,
    `| Total Score | ${safe(s?.totalScore)} |`,
    `| Frames Captured | ${safe(s?.totalFrames)} |`,
    ``,
  ];

  if (data.biomechanics) {
    const b = data.biomechanics;
    const stdDev = calculateStdDev(b.repScores);
    lines.push(`## Form Compliance`, ``);
    lines.push(`| Metric | Value |`);
    lines.push(`|--------|-------|`);
    lines.push(`| Reps Evaluated | ${b.repScores.length} |`);
    lines.push(`| Average Score | ${Math.round(b.averageScore * 100) / 100}% |`);
    lines.push(`| Score Range | ${Math.round(b.minScore)}% – ${Math.round(b.maxScore)}% |`);
    if (stdDev !== null) lines.push(`| Score Std Dev | ${stdDev} |`);
    if (b.tempoRatio) lines.push(`| Tempo Ratio | ${safe(b.tempoRatio)} |`);
    lines.push(``);
  }

  if (data.risk) {
    lines.push(`## Risk Assessment`, ``);
    lines.push(`| Metric | Value |`);
    lines.push(`|--------|-------|`);
    lines.push(`| Risk Index | ${Math.round(data.risk.riskIndex)}/100 |`);
    lines.push(`| Fatigue Index | ${Math.round(data.risk.fatigueIndex)}/100 |`);
    lines.push(`| Asymmetry Score | ${Math.round(data.risk.asymmetryScore)}/100 |`);
    lines.push(`| Risk Snapshots | ${data.risk.riskHistory.length} |`);
    lines.push(``);
  }

  const mistakes = s?.mistakes ? Object.entries(s.mistakes).sort((a, b) => b[1] - a[1]) : [];
  if (mistakes.length > 0) {
    lines.push(`## Error Log`, ``);
    lines.push(`| Issue | Count |`);
    lines.push(`|-------|-------|`);
    for (const [msg, count] of mistakes) {
      lines.push(`| ${safe(msg)} | ${count} |`);
    }
    lines.push(``);
  }

  lines.push(`---`);
  lines.push(`*SpectraX Compliance Report · ${new Date().toISOString()} · Version 1.0*`);
  lines.push(`*This report is an audit-quality record of on-device pose analysis data.*`);

  return lines.join("\n");
}

